const OUTPUT_MESSAGES: Readonly<Record<OutputRefusedCode, string>> = {
  exists: "the target already exists (use --force to replace it)",
  symlink: "refusing to write through a symlink",
  "parent-invalid": "the parent directory is missing or not a directory",
  "not-regular": "the target exists and is not a regular file or directory of the expected kind",
  "not-marked": "the directory exists and was not generated by swain ui (no .atm-ui marker)",
  "too-large": "the output exceeds the size limit",
  "invalid-path": "the output path is invalid",
  "invalid-name": "an output file name is invalid",
  "stale-temp": "a leftover temporary output exists next to the target; remove it and retry",
  io: "filesystem error while writing the output",
};

function dispatch(
  inv: CommandInvocation,
  io: CliIo,
  out: (s: string) => void,
  err: (s: string) => void,
): number {
  const ctx: Ctx = {
    out,
    err,
    env: io.env,
    homeDir: homeDirOf(io.env),
    realHomeDir: realHomeOf(homeDirOf(io.env)),
    nowMs: io.nowMs,
    inv,
  };
  try {
    switch (inv.command) {
      case "import":
        return runImportCommand(ctx);
      case "sessions":
      case "list":
        return runSessions(ctx);
      case "show":
        return runShow(ctx);
      case "explain":
        return runExplain(ctx);
      case "report":
        return runReport(ctx);
      case "commands":
        return runCommands(ctx);
      case "ui":
        return runUi(ctx);
      case "sources":
        return runSources(ctx);
    }
  } catch (e) {
    // M1: static messages only; never err.message or a stack.
    if (e instanceof StoreError) {
      err(`swain: store error (${e.code}): ${STORE_MESSAGES[e.code]}\n`);
      return EXIT.store;
    }
    if (e instanceof OutputRefused) {
      err(`swain: output refused (${e.code}): ${OUTPUT_MESSAGES[e.code]}\n`);
      return EXIT.outputRefused;
    }
    if (e instanceof OutputTooLarge) {
      err("swain: output refused (too-large): the rendering exceeds the size limit\n");
      return EXIT.outputRefused;
    }
    throw e;
  }
}

/** Stops writing after the first EPIPE: a closed pipe is not an error worth reporting. */
function quiet(w: CliWriter): (s: string) => void {
  let closed = false;
  if (typeof w.on === "function") w.on("error", () => undefined);
  return (s) => {
    if (closed) return;
    try {
      w.write(s);
    } catch (e) {
      const code = typeof e === "object" && e !== null ? (e as { code?: unknown }).code : undefined;
      if (code === "EPIPE") {
        closed = true;
        return;
      }
      throw e;
    }
  };
}

/**
 * Never writes err.message or err.stack, and never writes untrusted data except through the
 * escapers in text.ts.
 */
export function main(argv: readonly string[], io: CliIo): number {
  const out = quiet(io.stdout);
  const err = quiet(io.stderr);
  const parsed = parseArgs(argv);
  switch (parsed.kind) {
    case "version":
      out(`swain ${CLI_VERSION}\ncanonical-schema ${SCHEMA_VERSION}\n`);
      return EXIT.ok;
    case "help":
      out(USAGE);
      return EXIT.ok;
    case "usage":
      err(USAGE);
      return EXIT.usage;
    case "error":
      err(parsed.message);
      return EXIT.usage;
    case "command":
      return dispatch(parsed.invocation, io, out, err);
  }
}

/** Wraps `main`; on any throw prints only a static message and returns 1 (N8). */
export function runMain(argv: readonly string[], io: CliIo): number {
  try {
    return main(argv, io);
  } catch {
    try {
      io.stderr.write("swain: internal error\n");
    } catch {
      // nothing else may be written
    }
    return EXIT.internal;
  }
}
